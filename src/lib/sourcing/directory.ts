// The directory: companies the Rep watches for everyone, before any candidate
// asks. Two kinds, because the question each one answers is different:
//
//   spain       built here or with its main tech team here. Most offers are
//               in Spain; the question is only whether the role fits.
//   hires-spain based elsewhere, but hires people who live in Spain (a hub in
//               Madrid or Barcelona, or remote across Europe). Many of their
//               offers are not open to Spain; the matcher reads each one's
//               location against the candidate's rules.
//
// Only name and domain are required. careersUrl is given when the careers page
// is not at an obvious address; the board behind it is found by detection. A
// board is pinned (ats:token) only when detection cannot find it: the careers
// page is rendered in the browser and the board is not under the company's
// name (TravelPerk hires on Ashby as "perk").

import type { AtsKind } from './types'

export type DirectorySegment = 'spain' | 'hires-spain'

export interface DirectoryEntry {
  name: string
  domain: string
  segment: DirectorySegment
  careersUrl?: string
  board?: { ats: AtsKind; token: string }
  // Publishes the salary in its offers (getmanfred/companies-with-public-salary).
  publicSalary?: boolean
}

function entry(segment: DirectorySegment, name: string, domain: string, where?: string): DirectoryEntry {
  if (!where) return { name, domain, segment }
  const pinned = where.match(/^(greenhouse|lever|ashby|workable|teamtailor|recruitee|personio|bamboohr|workday|smartrecruiters|factorial|successfactors):(.+)$/)
  return pinned ? { name, domain, segment, board: { ats: pinned[1] as AtsKind, token: pinned[2] } } : { name, domain, segment, careersUrl: where }
}

const spain = (name: string, domain: string, where?: string) => entry('spain', name, domain, where)
const hires = (name: string, domain: string, where?: string) => entry('hires-spain', name, domain, where)

